const ARABIC_RE = /[\u0600-\u06FF]/;

export function containsArabic(value: string): boolean {
  return ARABIC_RE.test(value);
}

function normalizeLegacyKey(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

export function hasLegacyTranslation(value: string): boolean {
  const normalized = normalizeLegacyKey(value);
  return Boolean(legacyArabicToEnglish[normalized]);
}

function transliterateArabic(value: string): string {
  const chars: Record<string, string> = {
    "ا":"a","أ":"a","إ":"i","آ":"aa","ب":"b","ت":"t","ث":"th","ج":"j","ح":"h","خ":"kh","د":"d","ذ":"dh","ر":"r","ز":"z","س":"s","ش":"sh","ص":"s","ض":"d","ط":"t","ظ":"z","ع":"a","غ":"gh","ف":"f","ق":"q","ك":"k","ل":"l","م":"m","ن":"n","ه":"h","ة":"a","و":"w","ؤ":"o","ي":"y","ى":"a","ئ":"e","ء":"","َ":"","ُ":"","ِ":"","ّ":"","ْ":"","ً":"","ٌ":"","ٍ":"","ـ":""
  };
  return Array.from(value).map((char) => chars[char] ?? char).join("");
}

function translateTokens(value: string): string {
  let result = value;
  const phrases = Object.entries(legacyArabicToEnglish).sort((a, b) => b[0].length - a[0].length);
  for (const [arabic, english] of phrases) {
    if (result.includes(arabic)) result = result.split(arabic).join(english);
  }
  result = result.replace(/[\u0600-\u06FF]+/g, (word) => tokenMap[word] ?? transliterateArabic(word));
  return result.replace(/\s+/g, " ").trim();
}

export function translateLegacyText(value: string, language: Language, options?: { fallbackToTransliteration?: boolean }): string {
  if (language === "ar" || !containsArabic(value)) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const normalized = normalizeLegacyKey(value);
  const exact = legacyArabicToEnglish[normalized];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, replacement] of phraseReplacements) {
    if (pattern.test(normalized)) {
      const rough = normalized.replace(pattern, replacement);
      const translated = translateTokens(rough);
      if (!containsArabic(translated)) return `${leading}${translated}${trailing}`;
    }
  }

  if (!options?.fallbackToTransliteration) return value;
  return `${leading}${translateTokens(normalized)}${trailing}`;
}
